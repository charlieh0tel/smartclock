"""Renders the SCPI trees by model, every command path each firmware
image's parser knows side by side against the manuals, as a page that
filters them, from DATA, what `smartclock-cli dump-scpi --models
--json` prints, to OUT.  `make scpi-models` writes it among the
generated pages, which .github/workflows/pages.yml publishes on GitHub
Pages; the page is not committed.

    python3 -I tools/scpi_models.py DATA OUT

DATA, one JSON object:

    images     each image's name, the columns' order
    manuals    each manual: letter (the Manuals column's name for it),
               name (its document number), model
    sections   the rows by section, a top-level keyword's or the common
               commands', {name, rows}; each row: lead (the path
               shown), also (the other paths reaching its node, each as
               it differs from the lead), cells (each image's: q, s,
               qs, - or blank, docs/scpi/models.md's), manuals (the
               letters of those listing any of its paths), confirmed
               (the receivers that have answered one)
"""

import argparse
import html
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from pages_matrix import checkbox, page, select  # noqa: E402
from pages_render import BLOB  # noqa: E402

GENERATED = "tools/scpi_models.py by make scpi-models"

# Builds a row's cells, and the page's filters by control.
SCRIPT = """\
matrix({
  columns: ['Path', 'Manuals', 'Confirmed', ...DATA.images],
  sections: DATA.sections,
  row: row => {
    const path = td(row.lead, 'lead');
    if (row.also.length) {
      const also = document.createElement('span'); also.className = 'also';
      also.textContent = 'also ' + row.also.join(', '); path.appendChild(also);
    }
    return [path, td(row.manuals.join(', ')), td(row.confirmed.join(', ')), ...row.cells.map(c => td(c, 'cell'))];
  },
  words: row => row.lead + ' ' + row.also.join(' '),
  tests: {
    undocumented: m => m.data.manuals.length === 0,
    differs: m => new Set(m.data.cells).size > 1,
    handler: m => m.data.cells.some(c => c.includes('q') || c.includes('s')),
    image: (m, image) => m.data.cells[image] !== '',
  },
});
"""


def intro(data):
    manuals = "; ".join(f"{html.escape(m['letter'])}, {html.escape(m['name'])} ({html.escape(m['model'])})"
                        for m in data["manuals"])
    models = f'<a href="{BLOB}docs/scpi/models.md"><code>docs/scpi/models.md</code></a>'
    readme = f'<a href="{BLOB}docs/scpi/README.md"><code>docs/scpi/README.md</code></a>'
    return (f'<p class="muted">Every command path each firmware image\'s parser knows, side by side, one row per '
            "node: paths that reach the same node in every image that holds them share a row, the others listed "
            "under it. A cell is <code>q</code> for a query handler, <code>s</code> a setter, <code>qs</code> "
            f"both, <code>-</code> neither, blank where the image has no such path. Manuals: {manuals}. Confirmed "
            "names the bench receiver that has answered the path's command table entry.</p>\n"
            '<p class="muted">Generated by <code>smartclock-cli dump-scpi --models --json</code> and '
            f"<code>tools/scpi_models.py</code>, like {models}; {readme} says how the trees are read.</p>")


def render(data):
    return page(
        title="SCPI Trees by Model",
        description="Every command path each SmartClock firmware image's SCPI parser knows, side by side "
                    "against the manuals, as a table that filters.",
        group="scpi",
        generated=GENERATED,
        heading="SCPI trees by model",
        intro=intro(data),
        placeholder="Filter paths, e.g. holdover",
        controls=[
            checkbox("undocumented", "In no manual"),
            checkbox("differs", "Differs between images"),
            checkbox("handler", "Has a handler"),
            select("image", "Image", enumerate(data["images"])),
        ],
        data=data,
        script=SCRIPT,
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("data", type=Path, help="dump-scpi --models --json's output")
    parser.add_argument("out", type=Path, help="the page to write")
    args = parser.parse_args()
    data = json.loads(args.data.read_text(encoding="utf-8"))
    args.out.write_text(render(data), encoding="utf-8")


if __name__ == "__main__":
    main()
